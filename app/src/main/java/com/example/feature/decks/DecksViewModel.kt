package com.example.feature.decks

import android.app.Application
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.example.core.database.entity.SchoolMaterialEntity
import com.example.core.database.entity.StudyDeckEntity
import com.example.core.repository.StudyLockRepository
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch

data class DecksUiState(
    val decks: List<StudyDeckEntity> = emptyList(),
    val schoolMaterials: List<SchoolMaterialEntity> = emptyList(),
    val isAutoGenerating: Boolean = false,
    val isLoading: Boolean = true
)

class DecksViewModel(application: Application) : AndroidViewModel(application) {

    private val repository = StudyLockRepository(application)

    private val _uiState = MutableStateFlow(DecksUiState())
    val uiState: StateFlow<DecksUiState> = _uiState.asStateFlow()

    init {
        loadData()
    }

    private fun loadData() {
        viewModelScope.launch {
            repository.allDecksFlow.collect { deckList ->
                val materials = repository.database.schoolMaterialDao().getAllMaterialsList()
                _uiState.value = _uiState.value.copy(
                    decks = deckList,
                    schoolMaterials = materials,
                    isLoading = false
                )
            }
        }
    }

    fun deleteDeck(deck: StudyDeckEntity) {
        viewModelScope.launch {
            repository.deleteDeck(deck)
        }
    }

    fun createDeck(title: String, subject: String, content: String, onCreated: (Long) -> Unit) {
        viewModelScope.launch {
            val id = repository.createDeck(title, subject, "Manual Deck", content)
            repository.generateAndSaveDeckContent(id, content, 5, 5)
            onCreated(id)
        }
    }

    fun autoGenerateAllDecks(onComplete: (Int) -> Unit) {
        viewModelScope.launch {
            _uiState.value = _uiState.value.copy(isAutoGenerating = true)
            val createdCount = repository.autoGenerateAllDecksFromSchoolMaterials()
            _uiState.value = _uiState.value.copy(isAutoGenerating = false)
            onComplete(createdCount)
        }
    }

    fun createDeckFromMaterial(materialId: Long, onCreated: (Long) -> Unit) {
        viewModelScope.launch {
            val newDeckId = repository.autoGenerateDeckFromSchoolMaterial(materialId)
            if (newDeckId != null) {
                onCreated(newDeckId)
            }
        }
    }
}
